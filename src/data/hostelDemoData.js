/**
 * Calculates due status (paid, critical overdue, warning overdue, today, upcoming)
 */
export const calculateDueStatus = (due) => {
  if (due.status === "paid") {
    return {
      key: "paid",
      label: "Paid",
      days: 0,
    };
  }

  const today = new Date();
  today.setHours(0, 0, 0, 0);

  const dueDate = new Date(`${due.dueDate}T00:00:00`);
  const difference = Math.floor((today - dueDate) / (1000 * 60 * 60 * 24));

  if (difference >= 3) {
    return {
      key: "critical",
      label: `${difference} Days Overdue`,
      days: difference,
    };
  }

  if (difference > 0) {
    return {
      key: "warning",
      label: `${difference} Day${difference > 1 ? "s" : ""} Overdue`,
      days: difference,
    };
  }

  if (difference === 0) {
    return {
      key: "today",
      label: "Due Today",
      days: 0,
    };
  }

  return {
    key: "upcoming",
    label: "Upcoming",
    days: Math.abs(difference),
  };
};
